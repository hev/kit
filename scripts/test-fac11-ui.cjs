// NODE_PATH=<temporary playwright node_modules> node scripts/test-fac11-ui.cjs
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
// Filters are layer-ui chips: open the field's picker, then toggle a value in it.
const pickFilter=async(page,key,value)=>{
 const chip=page.locator(`.live-filter:has(> span:text-is("${key}"))`);
 if(await chip.getAttribute('aria-expanded')!=='true')await chip.click();
 await page.locator(`#filter-editor .vs-option[title='${JSON.stringify(value)}']`).click();
};
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.HEV_DASHBOARD_URL||'http://127.0.0.1:18787';
 await page.goto(base+'/?window=all#traces');
 await page.waitForSelector('[data-trace-count="6"]');
 assert.equal(await page.locator('#archive-filters input[type=number]').count(),0);
 const search=await page.getByRole('textbox',{name:'Search traces',exact:true}).boundingBox();
 const facet=await page.locator('.live-filter:has(> span:text-is("project"))').boundingBox();
 assert.ok(search.y<facet.y);
 await pickFilter(page,'project','alpha');
 await page.waitForSelector('[data-trace-count="3"]');
 assert.equal(new URL(page.url()).searchParams.get('q'),null);
 await page.getByLabel('accuracy ceiling').selectOption('3');
 await page.waitForSelector('[data-trace-count="1"]');
 assert.match(await page.locator('#v-traces tbody').innerText(),/2·4·5·5/);
 const screenshotDir=process.env.HEV_SCREENSHOT_DIR||'docs/images';
 fs.mkdirSync(screenshotDir,{recursive:true});
 await page.screenshot({path:screenshotDir+'/fac11-filter-bar.png'});
 let requests=0;page.on('request',()=>requests++);
 const row=page.locator('#v-traces tbody tr').first();
 const before=requests;
 await row.hover();await page.waitForTimeout(150);
 assert.equal(await page.locator('#trace-preview').isVisible(),false);
 await page.locator('#trace-preview').waitFor({state:'visible'});
 assert.match(await page.locator('#trace-preview').innerText(),/Check the preflight/);
 assert.match(await page.locator('#trace-preview').innerText(),/accuracy 2\/5/);
 assert.equal(await page.locator('.tool-mix span').count(),1);
 await page.screenshot({path:screenshotDir+'/fac11-hover-card.png'});
 assert.equal(requests,before,'hover made a request');
 await page.mouse.move(0,0);await page.locator('#trace-preview').waitFor({state:'hidden'});
 await row.locator('a').first().focus();await page.locator('#trace-preview').waitFor({state:'visible'});
 await page.keyboard.press('Escape');await page.locator('#trace-preview').waitFor({state:'hidden'});
 assert.equal(requests,before,'focus made a request');
 await row.locator('a').first().click();await page.getByRole('button',{name:'Eval',exact:true}).click();
 await page.waitForSelector('#v-eval.on .eval-bar');
 assert.equal(await page.locator('.eval-bar').count(),4);
 assert.equal(await page.locator('.eval-tick').count(),8);
 assert.match(await page.locator('.eval-averages').first().innerText(),/all n=2.*avg 3.50/);
 assert.match(await page.locator('.eval-averages').first().innerText(),/alpha n=1/);
 await page.screenshot({path:screenshotDir+'/fac11-eval-bars.png',fullPage:true});
 await page.goto(base+'/?window=all#stats');
 await page.getByRole('button',{name:'custom',exact:true}).click();
 await page.getByLabel('since',{exact:true}).fill('2026-09-01');
 await page.getByLabel('until',{exact:true}).fill('2026-09-03');
 await page.waitForSelector('#range button.on:text-is("Sep 1 – Sep 3")');
 await page.waitForFunction(()=>!document.body.classList.contains('loading'));
 const url=new URL(page.url());assert.equal(url.searchParams.get('since'),'2026-09-01');
 assert.equal(url.searchParams.get('until'),'2026-09-04T00:00:00.000Z');
 const list=await page.request.get(base+'/api/sessions?'+url.searchParams);
 const stats=await page.request.get(base+'/api/stats?'+url.searchParams);
 assert.equal((await list.json()).sessions.length,(await stats.json()).traces);
 const all=await (await page.request.get(base+'/api/sessions?window=all')).json();
 const days=[...new Set(all.sessions.map(r=>new Date(r.start).toISOString().slice(0,10)))].sort();
 await page.getByLabel('until',{exact:true}).fill(days[1]);
 await page.getByLabel('since',{exact:true}).fill(days[0]);
 await page.waitForFunction(()=>!document.body.classList.contains('loading'));
 const narrowed=await (await page.request.get(base+'/api/sessions?'+new URL(page.url()).searchParams)).json();
 assert.equal(narrowed.sessions.length,4,'end day was excluded');
 await page.getByLabel('since',{exact:true}).fill('2026-09-01');
 await page.getByLabel('until',{exact:true}).fill('2026-09-03');
 await page.reload();await page.waitForSelector('#range button.on:text-is("Sep 1 – Sep 3")');
 await page.getByRole('button',{name:'7d',exact:true}).click();
 assert.equal(new URL(page.url()).searchParams.has('since'),false);
 assert.equal(new URL(page.url()).searchParams.has('until'),false);
 assert.equal(await page.locator('input[type=date]').count(),0);
 assert.deepEqual(errors,[]);
 console.log('PASS: facets without search; mark ceilings; custom inclusive dates and preset reset; 300ms hover/focus without requests; four Eval bars/eight ticks; screenshots');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
