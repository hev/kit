const maxWire = 1 << 20

type Endpoint struct {
	URL   string `toml:"url"`
	Token string `toml:"token"`
}
type NetworkConfig struct {
	Listen string              `toml:"listen"`
	Token  string              `toml:"token"`
	Hosts  map[string]Endpoint `toml:"hosts"`
}

func LoadNetworkConfig(path string) (NetworkConfig, error) {
	var cfg struct {
		Peers NetworkConfig `toml:"peers"`
	}
	if path == "" {
		path = os.Getenv("HEV_CONFIG")
	}
	if path == "" {
		home, _ := os.UserHomeDir()
		path = filepath.Join(home, ".hev", "config.toml")
	}
	_, err := toml.DecodeFile(path, &cfg)
	if os.IsNotExist(err) {
		err = nil
	}
	if err != nil {
		var parse toml.ParseError
		if errors.As(err, &parse) {
			return cfg.Peers, fmt.Errorf("invalid peers configuration at line %d", parse.Position.Line)
		}
		// Type errors are plain errors, but carry a numeric line prefix.
		// Extract only that number: the remaining diagnostic may contain secrets.
		var line int
		if n, _ := fmt.Sscanf(err.Error(), "toml: line %d", &line); n == 1 {
			return cfg.Peers, fmt.Errorf("invalid peers configuration at line %d", line)
		}
		return cfg.Peers, fmt.Errorf("invalid peers configuration in %s", path)
	}
	return cfg.Peers, nil
}

type enqueue struct {
	Target  string `json:"target"`
	From    string `json:"from"`
	Message string `json:"message"`
	ID      string `json:"id,omitempty"`
}
type delivery struct {
	Status string `json:"status"`
	Detail string `json:"detail"`
}

// Handler exposes enqueue only: remote clients cannot paste into terminals or consume receipts.
func (e *Engine) Handler(token string) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if token == "" || subtle.ConstantTimeCompare([]byte(r.Header.Get("Authorization")), []byte("Bearer "+token)) != 1 {
			http.Error(w, "unauthorized", http.StatusUnauthorized)
			return
		}
		if r.URL.Path != "/v1/peers/enqueue" {
			http.NotFound(w, r)
			return
		}
		if r.Method != http.MethodPost {
			w.WriteHeader(http.StatusMethodNotAllowed)
			return
		}
		var q enqueue
		dec := json.NewDecoder(http.MaxBytesReader(w, r.Body, maxWire))
		dec.DisallowUnknownFields()
		if err := dec.Decode(&q); err != nil {
			http.Error(w, "invalid enqueue request", 400)
			return
		}
		if dec.Decode(&struct{}{}) != io.EOF || q.Target == "" || strings.Contains(q.Target, "/") || strings.HasPrefix(q.Target, "-") || !validSender(q.From) || strings.IndexFunc(q.ID, unicode.IsControl) >= 0 || strings.TrimSpace(q.Message) == "" {
			http.Error(w, "invalid enqueue request", 400)
			return
		}
		var out bytes.Buffer
		// Require a registered inbox; no HTTP request can trigger terminal input.
		local := *e
		local.inboxOnly = true
		var status DeliveryStatus
		local.deliveryStatus = &status
		err := local.Run(r.Context(), []string{"send", q.Target, "-", "--from", q.From, "--id", q.ID}, strings.NewReader(q.Message), &out, io.Discard)
		d := delivery{Status: string(status), Detail: strings.TrimSpace(out.String())}
		if err != nil {
			d.Status = "failed"
			d.Detail = err.Error()
		}
		w.Header().Set("Content-Type", "application/json")
		json.NewEncoder(w).Encode(d)
	})
}

// StartListener is disabled unless listen is explicitly configured. The caller owns shutdown.
func StartListener(ctx context.Context, cfg NetworkConfig) (func(), error) {
	if cfg.Listen == "" {
		return func() {}, nil
	}
	if len(cfg.Token) < 32 {
		return nil, fmt.Errorf("peers listener requires a token of at least 32 characters")
	}
	ln, err := net.Listen("tcp", cfg.Listen)
	if err != nil {
		return nil, err
	}
	srv := &http.Server{Handler: New().Handler(cfg.Token), ReadHeaderTimeout: 5 * time.Second, ReadTimeout: 15 * time.Second, WriteTimeout: 15 * time.Second, IdleTimeout: 30 * time.Second, MaxHeaderBytes: 8192}
	done := make(chan struct{})
	go func() { _ = srv.Serve(ln); close(done) }()
	go func() {
		select {
		case <-ctx.Done():
			srv.Close()
		case <-done:
		}
	}()
	return func() { srv.Close(); <-done }, nil
}

type HEVDTransport struct {
	Hosts    map[string]Endpoint
	Fallback Transport
	Client   *http.Client
}

func (t HEVDTransport) Execute(ctx context.Context, host string, args []string, in io.Reader, out, errout io.Writer) error {
	ep, ok := t.Hosts[host]
	if !ok || len(args) == 0 || args[0] != "send" {
		return t.Fallback.Execute(ctx, host, args, in, out, errout)
	}
	// The remote argument layout is generated by Engine.Run, never a shell command.
	if len(args) < 3 {
		return fmt.Errorf("invalid remote send")
	}
	q := enqueue{Target: args[1], Message: args[2]}
	for i := 3; i < len(args); i++ {
		switch args[i] {
		case "--from", "--id":
			if i+1 >= len(args) {
				return fmt.Errorf("invalid remote send")
			}
			key := args[i]
			i++
			if key == "--from" {
				q.From = args[i]
			} else {
				q.ID = args[i]
			}
		case "--force":
		default:
			return fmt.Errorf("invalid remote send")
		}
	}
	if q.Message == "-" {
		b, err := io.ReadAll(io.LimitReader(in, maxWire+1))
		if err != nil {
			return err
		}
		q.Message = string(b)
	}
	b, _ := json.Marshal(q)
	if len(b) > maxWire {
		return fmt.Errorf("peers message exceeds wire limit")
	}
	u, err := url.Parse(ep.URL)
	if err != nil || (u.Scheme != "http" && u.Scheme != "https") || u.Host == "" || u.User != nil || u.RawQuery != "" || u.Fragment != "" || ep.Token == "" {
		return fmt.Errorf("invalid hevd endpoint configuration")
	}
	u.Path = strings.TrimRight(u.Path, "/") + "/v1/peers/enqueue"
	req, _ := http.NewRequestWithContext(ctx, http.MethodPost, u.String(), bytes.NewReader(b))
	req.Header.Set("Authorization", "Bearer "+ep.Token)
	req.Header.Set("Content-Type", "application/json")
	client := t.Client
	if client == nil {
		client = &http.Client{Timeout: 10 * time.Second}
	}
	// Never forward credentials through redirects.
	copyClient := *client
	copyClient.CheckRedirect = func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }
	resp, err := copyClient.Do(req)
	if err != nil {
		var op *net.OpError
		if errors.As(err, &op) && op.Op == "dial" {
			fmt.Fprintln(errout, "hevd unreachable; using ssh")
			fallback := t.Fallback
			if ssh, ok := fallback.(SSHTransport); ok {
				ssh.Quiet = true
				fallback = ssh
			}
			replay := []string{"send", q.Target, "-", "--from", q.From}
			if q.ID != "" {
				replay = append(replay, "--id", q.ID)
			}
			for _, a := range args {
				if a == "--force" {
					replay = append(replay, "--force")
				}
			}
			return fallback.Execute(ctx, host, replay, strings.NewReader(q.Message), out, errout)
		}
		return fmt.Errorf("hevd request failed; delivery outcome may be unknown; inspect before retrying")
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		return fmt.Errorf("hevd failed: HTTP %d", resp.StatusCode)
	}
	var d delivery
	if err := json.NewDecoder(io.LimitReader(resp.Body, maxWire)).Decode(&d); err != nil {
		return fmt.Errorf("invalid hevd response; delivery outcome may be unknown")
	}
	switch d.Status {
	case "delivered to session inbox", "delivered to run inbox", "queued for next round", "held for ended run":
		fmt.Fprintf(out, "via hevd: %s: %s\n", d.Status, d.Detail)
		return nil
	case "failed":
		return fmt.Errorf("hevd failed: %s", d.Detail)
	default:
		return fmt.Errorf("unknown hevd delivery status; inspect before retrying")
	}
}

func validSender(s string) bool {
	parts := strings.Split(s, "/")
	if len(parts) != 2 {
		return false
	}
	for _, part := range parts {
		if len(part) == 0 || len(part) > 255 || strings.HasPrefix(part, "-") {
			return false
		}
		for _, r := range part {
			if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '-' || r == '_' || r == '.') {
				return false
			}
		}
	}
	return true
}

type configuredTransport struct{ fallback Transport }

func (t configuredTransport) Execute(ctx context.Context, host string, args []string, in io.Reader, out, errout io.Writer) error {
	fallback := t.fallback
	if fallback == nil {
		fallback = SSHTransport{}
	}
	cfg, err := LoadNetworkConfig("")
	if err != nil {
		fmt.Fprintf(errout, "warning: %v; using ssh transport\n", err)
		return fallback.Execute(ctx, host, args, in, out, errout)
	}
	return (HEVDTransport{Hosts: cfg.Hosts, Fallback: fallback}).Execute(ctx, host, args, in, out, errout)
}
